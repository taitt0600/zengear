"""Tests of tools/comment_templates.py (DEC-148 (8), (9), DEC-150 (3), DEC-151 (1)): each structured comment renders
with its hidden marker, and parse() reads only a whole, valid marker, one per comment.

Run from the repository root: python3 -m unittest discover -s tools/tests -v
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import comment_templates as ct  # noqa: E402

SHA = 'a' * 40


class RenderParseTests(unittest.TestCase):
    def roundtrip(self, body, kind, fields):
        self.assertEqual(ct.parse(body), (kind, fields))

    def test_handoff(self):
        body = ct.handoff('STF-09', 8, branch='feat/stf-09', next_command='/finish-feature STF-09',
                          notes='Tests green, two Needs decision items left.')
        self.assertIn('/finish-feature STF-09', body)
        self.assertIn('feat/stf-09', body)
        self.roundtrip(body, 'handoff', {'feature': 'STF-09', 'step': '8'})

    def test_code_review(self):
        body = ct.code_review(SHA, 'pass', 'No Blocking item.')
        self.roundtrip(body, 'code-review', {'sha': SHA, 'verdict': 'pass'})
        self.roundtrip(ct.code_review(SHA, 'blocking', 'x'), 'code-review', {'sha': SHA, 'verdict': 'blocking'})

    def test_blocked_by_and_unblock(self):
        self.roundtrip(ct.blocked_by(12), 'blocked-by', {'issue': '12'})
        self.roundtrip(ct.unblock(12), 'unblock', {'issue': '12'})

    def test_blocked_by_result(self):
        body = ct.blocked_by_result(987654321, 'ok', 'blocked by #12')
        self.roundtrip(body, 'blocked-by-result', {'request': '987654321', 'result': 'ok'})

    def test_log_lines(self):
        for line in ct.LOG_LINES:
            self.roundtrip(ct.log_line(line, 'text'), 'log', {'line': line})

    def test_render_refuses_bad_values(self):
        for call in (lambda: ct.code_review('abc', 'pass', ''), lambda: ct.code_review(SHA, 'ok', ''),
                     lambda: ct.blocked_by(0), lambda: ct.blocked_by(-3), lambda: ct.handoff('stf-09', 8),
                     lambda: ct.log_line('other', ''), lambda: ct.blocked_by_result(1, 'maybe', '')):
            with self.assertRaises(ValueError):
                call()


class StrictParseTests(unittest.TestCase):
    def test_free_comment(self):
        self.assertIsNone(ct.parse('Looks good to me.'))
        self.assertIsNone(ct.parse(''))
        self.assertIsNone(ct.parse(None))

    def test_marker_must_start_a_line(self):
        self.assertIsNone(ct.parse('see <!-- zengear:blocked-by issue=12 -->'))

    def test_marker_inside_a_code_fence_or_quote_does_not_count(self):
        self.assertIsNone(ct.parse('> <!-- zengear:blocked-by issue=12 -->'))
        self.assertIsNone(ct.parse('```\n<!-- zengear:blocked-by issue=12 -->\n```'))

    def test_two_markers_are_refused(self):
        self.assertIsNone(ct.parse(ct.blocked_by(12) + '\n' + ct.blocked_by(13)))

    def test_bad_values(self):
        for body in ('<!-- zengear:blocked-by issue=012 -->', '<!-- zengear:blocked-by issue=1e3 -->',
                     '<!-- zengear:blocked-by issue=١٢ -->', '<!-- zengear:blocked-by -->',
                     '<!-- zengear:blocked-by issue=12 extra=1 -->', '<!-- zengear:code-review sha=abc verdict=pass -->',
                     f'<!-- zengear:code-review sha={SHA.upper()} verdict=pass -->',
                     f'<!-- zengear:code-review sha={SHA} verdict=PASS -->', '<!-- zengear:unknown x=1 -->',
                     '<!-- zengear:blocked-by issue=12 issue=13 -->'):
            self.assertIsNone(ct.parse(body), body)

    def test_crlf_and_trailing_text(self):
        self.assertEqual(ct.parse('<!-- zengear:unblock issue=7 -->\r\nThe blocker is done.'),
                         ('unblock', {'issue': '7'}))

    def test_footer_of_the_cloud_harness_is_ignored(self):
        body = ct.blocked_by(12) + '\n\n---\nGenerated by a Claude Code cloud session: https://claude.ai/code/x'
        self.assertEqual(ct.parse(body), ('blocked-by', {'issue': '12'}))


if __name__ == '__main__':
    unittest.main()
